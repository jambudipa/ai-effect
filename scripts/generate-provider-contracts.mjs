import assert from 'node:assert/strict';
import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import ts from 'typescript';
import { zodDiscriminatorEdit } from './zod-discriminator-edits.mjs';

/** Select the provider SDKs from the wrapper's dependency installation. */
const require = createRequire(import.meta.url);
/** Find the lockstep pins and export report relative to this script. */
const root = fileURLToPath(new URL('..', import.meta.url));
/** Preserve the type contract's relative layout between source and dist. */
const contracts = 'internal/provider-contracts';
/** Keep checked-in provider types and upstream licenses together. */
const sourceDirectory = join(root, 'src', contracts);
/** Copy the same relative module paths into the built npm package. */
const distDirectory = join(root, 'dist', contracts);

if (process.argv.includes('--copy-to-dist')) {
  await cp(sourceDirectory, distDirectory, { recursive: true });
  process.exit(0);
}

/** Verify generated bytes without rewriting the checked-in contracts in CI. */
const check = process.argv.includes('--check');
/** Compare or write each generated contract and license according to the selected mode. */
const write = async (filename, content) => {
  const file = join(sourceDirectory, filename);
  if (check) {
    assert.equal(
      await readFile(file, 'utf8'),
      content,
      `Stale contract: ${file}`,
    );
  } else {
    await mkdir(sourceDirectory, { recursive: true });
    await writeFile(file, content);
  }
};
/** Parse metadata from UTF-8 so license and declaration paths come from the same installation. */
const readJson = async (file) => JSON.parse(await readFile(file, 'utf8'));
/** Read the exact dependency versions required by the wrapper. */
const manifest = await readJson(join(root, 'package.json'));
/** Read the baseline used to select each public provider declaration. */
const surface = await readJson(join(root, 'docs/sdk-surface.json'));
/** Drop upstream comments before formatting the projected contracts. */
const printer = ts.createPrinter({ removeComments: true });
/** Require the known count of Zod discriminator edits for each provider pin. */
const replacements = new Map([
  ['openai', 2],
  ['heygen', 5],
  ['azure', 0],
]);
/** Deduplicate identical upstream licenses in the generated directory. */
const licenses = new Map();

/** Project Azure's OpenAI types and tool factories through the public local OpenAI contract. */
function azureContract(source) {
  const internal =
    /import \{([^}]+)\} from ["']@ai-sdk\/openai\/internal["'];/u;
  const original = source.match(internal);
  assert.ok(original, 'Azure must declare the pinned OpenAI imports');
  const names = original[1].split(',').map((name) => name.trim());
  const metadata = names.filter((name) => name.startsWith('Responses'));
  const factories = names.filter((name) => !metadata.includes(name));
  const bindings = metadata.map((name) => `Openai${name} as ${name}`);
  const imports = `import type { OpenAIProvider, ${bindings.join(', ')} } from './openai.js';`;
  let result = source.replace(internal, imports);
  for (const factory of factories) {
    const callable = `typeof ${factory};`;
    assert.ok(result.includes(callable), `Missing Azure tool ${factory}`);
    result = result.replace(callable, `OpenAIProvider['tools']['${factory}'];`);
  }
  return result.replaceAll('"@ai-sdk/openai"', '"./openai.js"');
}

for (const [provider, expected] of replacements) {
  const upstream = `@ai-sdk/${provider}`;
  const installedManifest = require.resolve(`${upstream}/package.json`);
  const dir = dirname(installedManifest);
  const { version } = await readJson(installedManifest);
  assert.equal(
    version,
    manifest.dependencies[upstream],
    `Pin differs for ${upstream}`,
  );
  const target = surface.paths.find((entry) => entry.upstream === upstream)
    .resolvers['node-import'].types;
  const license = await readFile(join(dir, 'LICENSE'), 'utf8');
  const licenseFile = licenses.get(license) ?? `${provider}.LICENSE`;
  licenses.set(license, licenseFile);

  const filename = `${provider}.d.ts`;
  const original = await readFile(join(dir, target), 'utf8');
  const text = provider === 'azure' ? azureContract(original) : original;
  const parse = (text) =>
    ts.createSourceFile(filename, text, ts.ScriptTarget.Latest, true);
  const source = parse(text);
  const edits = [];
  const visit = (node) => {
    const edit = zodDiscriminatorEdit(node, source);
    if (edit) edits.push(edit);
    node.forEachChild(visit);
  };
  visit(source);
  assert.equal(
    edits.length,
    expected,
    `Zod union count differs for ${upstream}`,
  );
  const normalized = edits
    .sort((left, right) => right[0] - left[0])
    .reduce(
      (content, [start, end, replacement]) =>
        content.slice(0, start) + replacement + content.slice(end),
      text,
    );
  const header = [
    `// Generated from ${upstream}@${version}. Do not edit.`,
    `// Original license: ${licenseFile}.`,
    ...(edits.length > 0
      ? [
          '// Preserve discriminator literals with the Zod 3.25.76 bridge.',
          '/* eslint-disable effect/no-zod-use-schema -- Pinned SDK declaration types use Zod. */',
        ]
      : []),
    '',
  ].join('\n');
  const filepath = join(sourceDirectory, filename);
  await write(
    filename,
    await format(header + printer.printFile(parse(normalized)), {
      ...(await resolveConfig(filepath)),
      filepath,
    }),
  );
}

for (const [content, filename] of licenses) await write(filename, content);

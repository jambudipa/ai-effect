import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { format } from 'prettier';
import ts from 'typescript';
import { findSdkOperations } from './sdk-declaration-graph.mjs';

/** Select byte verification in CI or regenerate the simple utility adapter file. */
const { values } = parseArgs({ options: { check: { type: 'boolean' } } });
/** Anchor the SDK declaration and generated output in the repository root. */
const project = fileURLToPath(new URL('..', import.meta.url));
/** Restrict the generator to the public provider utility entry. */
const packageName = '@ai-sdk/provider-utils';
/** Use the pinned runtime and declaration routes from the committed inventory. */
const baseline = JSON.parse(
  await readFile(join(project, 'docs/sdk-surface.json'), 'utf8'),
);
/** Read the selected manifest branches before comparing runtime and type names. */
const { targets, resolvers } = baseline.paths.find(
  ({ upstream }) => upstream === packageName,
);
/** Require a runtime export before emitting a callable adapter. */
const runtime = new Set(targets[resolvers['node-import'].runtime].names);
/** Open the declaration file for the same ESM route as the runtime inventory. */
const declaration = join(
  project,
  'node_modules',
  packageName,
  resolvers['node-import'].types,
);
/** Build a strict declaration graph with the installed SDK as its input. */
const program = ts.createProgram([declaration], {
  module: ts.ModuleKind.NodeNext,
  target: ts.ScriptTarget.ES2022,
  strict: true,
  skipLibCheck: true,
  types: ['node'],
});
/** Inspect call signatures and result types without loading the SDK runtime. */
const checker = program.getTypeChecker();
/** Read the already loaded declaration AST for its module symbol. */
const source = program.getSourceFile(declaration);
/** Limit candidates to the selected SDK module's own public exports. */
const namespace = checker.getSymbolAtLocation(source);

/** Reject callable, host, resource, or nested operation types that need a specialized adapter. */
function isDataType(type) {
  if (type.isUnionOrIntersection()) return type.types.every(isDataType);
  if (type.flags & ts.TypeFlags.Any) return false;
  if (checker.getSignaturesOfType(type, ts.SignatureKind.Call).length)
    return false;
  if (checker.getSignaturesOfType(type, ts.SignatureKind.Construct).length)
    return false;
  const name = type.getSymbol()?.name;
  if (
    name &&
    /^(?:AsyncIterable|Iterable|ReadableStream|WritableStream|TransformStream|File|Response|Request)$/u.test(
      name,
    )
  )
    return false;
  return !findSdkOperations(checker, [], [{ type, path: 'signature' }]).length;
}

/** Select simple synchronous single-signature functions with data-only inputs and results. */
const names = checker
  .getExportsOfModule(namespace)
  .filter((exported) => {
    if (!runtime.has(exported.name)) return false;
    const symbol =
      exported.flags & ts.SymbolFlags.Alias
        ? checker.getAliasedSymbol(exported)
        : exported;
    const type = checker.getTypeOfSymbol(symbol);
    const calls = checker.getSignaturesOfType(type, ts.SignatureKind.Call);
    if (calls.length !== 1 || checker.getPropertiesOfType(type).length)
      return false;
    const [call] = calls;
    if (
      call.getTypeParameters()?.length ||
      checker.getTypePredicateOfSignature(call)
    )
      return false;
    const result = checker.getReturnTypeOfSignature(call);
    if (checker.getAwaitedType(result) !== result) return false;
    return (
      call
        .getParameters()
        .every((parameter) => isDataType(checker.getTypeOfSymbol(parameter))) &&
      isDataType(result)
    );
  })
  .map(({ name }) => name)
  .sort();

/** Wrap each supported call in the same lazy Effect error boundary. */
const functions = names.map(
  (name) =>
    `export const ${name} = (...args: Parameters<typeof sdk.${name}>) => runSync('provider-utils.${name}', () => sdk.${name}(...args));`,
);
/** Format generated source deterministically before writing or comparing it. */
const content = await format(
  `// Generated by scripts/generate-sdk-simple-functions.mjs.
import * as sdk from '${packageName}';
import { runSync } from '../internal/operation.js';
${functions.join('\n\n')}
`,
  { parser: 'typescript', singleQuote: true },
);
/** Keep generated synchronous utility wrappers in the provider protocol layer. */
const output = join(project, 'src/protocols/provider-utils-simple.ts');
if (values.check)
  assert.equal(
    content,
    await readFile(output, 'utf8'),
    'SDK simple functions changed',
  );
else await writeFile(output, content);
console.log(`Checked ${names.length} simple provider utility functions`);

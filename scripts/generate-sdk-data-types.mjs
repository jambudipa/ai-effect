import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { format } from 'prettier';
import ts from 'typescript';
import { findSdkOperations } from './sdk-declaration-graph.mjs';

const { values } = parseArgs({ options: { check: { type: 'boolean' } } });
const project = fileURLToPath(new URL('..', import.meta.url));
const baseline = JSON.parse(
  await readFile(join(project, 'docs/sdk-surface.json'), 'utf8'),
);
const entries = baseline.paths.filter(({ upstream }) =>
  /^(?:ai(?:\/test)?|@ai-sdk\/(?:provider|provider-utils(?:\/[\w-]+)?))$/u.test(
    upstream,
  ),
);

const outputs = new Map([
  ['ai', 'core'],
  ['ai/test', 'testing'],
  ['@ai-sdk/provider', 'provider'],
]);
const adaptations = new Map([
  ['ai', new Set(['IdGenerator', 'TimeoutConfiguration'])],
]);

const options = {
  module: ts.ModuleKind.NodeNext,
  target: ts.ScriptTarget.ES2022,
  strict: true,
  skipLibCheck: true,
  types: ['node'],
};

const files = entries.map(({ upstream, resolvers }) => {
  const packageName = upstream.match(/^(@[^/]+\/[^/]+|[^/]+)/u)[0];
  return join(
    project,
    'node_modules',
    packageName,
    resolvers['node-import'].types,
  );
});
const program = ts.createProgram(files, options);
const checker = program.getTypeChecker();

function dataNames(file, entry) {
  const source = program.getSourceFile(file);
  assert.ok(source, `Missing pinned SDK declarations for ${entry}`);
  const namespace = checker.getSymbolAtLocation(source);
  return checker
    .getExportsOfModule(namespace)
    .filter((symbol) => {
      if (adaptations.get(entry)?.has(symbol.name)) return false;
      const resolved =
        symbol.flags & ts.SymbolFlags.Alias
          ? checker.getAliasedSymbol(symbol)
          : symbol;
      if (
        !(resolved.flags & ts.SymbolFlags.Type) ||
        resolved.flags & ts.SymbolFlags.Value
      )
        return false;
      return findSdkOperations(checker, [symbol]).length === 0;
    })
    .map(({ name }) => name)
    .sort();
}

let total = 0;
for (const [index, { upstream }] of entries.entries()) {
  const names = dataNames(files[index], upstream);
  const target = outputs.get(upstream) ?? upstream.replace(/^@ai-sdk\//u, '');
  const file = join(project, 'src/internal/sdk-data', `${target}.ts`);
  const exports = names.length
    ? `export type { ${names.join(', ')} } from '${upstream}';`
    : 'export {};';
  const source = await format(
    `// Generated by scripts/generate-sdk-data-types.mjs.\n${exports}\n`,
    { parser: 'typescript', singleQuote: true },
  );
  if (values.check)
    assert.equal(
      source,
      await readFile(file, 'utf8'),
      `SDK data types changed for ${upstream}`,
    );
  else {
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, source);
  }
  total += names.length;
}
console.log(
  `Checked ${total} data types across ${entries.length} SDK import paths`,
);
